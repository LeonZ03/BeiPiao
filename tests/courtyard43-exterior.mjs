import fs from 'node:fs';
import assert from 'node:assert/strict';
import * as THREE from '../room-site/dist/vendor/three.module.js';
import {parseBlenderRoom} from '../room-site/dist/blender-room.js';
const base=new URL('../room-site/dist/assets/rooms/Courtyard43/interior/',import.meta.url);
const manifest=JSON.parse(fs.readFileSync(new URL('scene.json',base),'utf8'));
const b=fs.readFileSync(new URL('geometry.bin',base));
const {world}=parseBlenderRoom(THREE,manifest,b.buffer.slice(b.byteOffset,b.byteOffset+b.byteLength),manifest.textures.map(()=>new THREE.Texture()));
world.updateMatrixWorld(true);
assert.ok(!world.getObjectByName('C43_Exterior_Masonry'),'Obsolete wall must not occlude the new courtyard');
assert.ok(!world.getObjectByName('C43_Exterior_Windows'));
const exterior=world.getObjectByName('C43_ZWinter');
assert.ok(exterior.userData.noCollision&&exterior.userData.cutaway);
assert.ok(!manifest.interactions.some(x=>manifest.nodes[x.node].name.startsWith('C43_ZWinter')));
const groupBounds=prefix=>{const box=new THREE.Box3();exterior.traverse(o=>{if(o.isMesh&&o.name.startsWith('C43_ZWinter_'+prefix))box.union(new THREE.Box3().setFromObject(o));});assert.ok(!box.isEmpty(),prefix);return box;};
const canopy=groupBounds('Canopy'),bikes=groupBounds('ParkedBikes'),roof=groupBounds('CorrugatedRoofSnow'),main=groupBounds('MainApartment'),right=groupBounds('RightBlock'),gap=groupBounds('YellowGap');
assert.ok(bikes.max.y<groupBounds('CanopySnow').min.y,'Bikes remain below the wire canopy');
assert.ok(canopy.max.z < -1.2 && canopy.min.z>roof.max.z-.1,'Near grid, then low roof');
assert.ok(roof.min.z>main.max.z,'Apartment stands behind the roof');
assert.ok(right.min.x>main.max.x+8,'Open sky gap is retained between residential blocks');
assert.ok(gap.max.x>main.max.x&&gap.min.z<main.min.z,'Pale far building is visible in the gap');
assert.ok(bikes.min.y>=-3.12&&bikes.min.y< -3.04,'Wheels meet snowy ground');
const glazing=manifest.materials.find(m=>m.name==='C43_Clear_window_glass');
assert.ok(glazing.props.opacity<.08&&glazing.props.depthWrite===false,'Clear glazing avoids an opaque veil');
// A downward oblique ray reaches the ground through genuine grid openings.
const ray=new THREE.Raycaster(new THREE.Vector3(.123,1.58,-.73),new THREE.Vector3(.01,-1,-1).normalize());
const targets=[];exterior.traverse(o=>{if(o.isMesh&&/Canopy|Ground/.test(o.name))targets.push(o);});
assert.ok(ray.intersectObjects(targets,false).some(h=>h.object.name.includes('Ground')));
console.log('PASS Courtyard43 winter exterior: depth layers, open canopy, sky gap, supported bikes, isolated non-interactive background and clear glazing.');
