import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';

const source=fs.readFileSync(new URL('../room-site/dist/archive.js',import.meta.url),'utf8');
const nodes=new Map(),listeners=new Map();
let directoryCloses=0,enterFocuses=0;
const node=id=>{if(!nodes.has(id))nodes.set(id,{hidden:id==='app'||id==='courtyardRoom',addEventListener(name,fn){listeners.set(`${id}:${name}`,fn);},close(){if(id==='directoryDialog')directoryCloses++;},focus(){if(id==='enterRoomBtn')enterFocuses++;},setAttribute(name,value){this[name]=value;}});return nodes.get(id);};
for(const id of ['roomNumber','roomTitle','archiveCover','enterRoomBtn'])node(id);
const directory=node('directoryDialog');
const makeChoice=(id,inDirectory=false)=>({dataset:{roomSelect:id},setAttribute(name,value){this[name]=value;},addEventListener(name,fn){this.click=fn;},closest(selector){if(selector==='dialog'&&inDirectory)return directory;if(selector==='li'&&!inDirectory)return {classList:{toggle(){}}};return null;}});
const choices=[makeChoice('yongwang-jiayuan'),makeChoice('Courtyard43'),makeChoice('yongwang-jiayuan',true),makeChoice('Courtyard43',true)];
const doc={fullscreenElement:null,title:'',getElementById:node,querySelectorAll:()=>choices};
node('roomNumber').textContent='ROOM 01';node('roomTitle').textContent='永旺家园';node('archiveCover').src='./assets/archive-hero.png';node('enterRoomBtn').href='#room';
const location={hash:'',origin:'https://room.example'};
const context=vm.createContext({document:doc,location,window:{addEventListener:(name,fn)=>listeners.set(`window:${name}`,fn)},console});
const loader=new vm.SyntheticModule(['startRoomLoading','failRoomLoading'],function(){this.setExport('startRoomLoading',()=>{});this.setExport('failRoomLoading',()=>{});},{context});
const archive=new vm.SourceTextModule(source,{context,importModuleDynamically:async()=>{throw Error('Homepage selection must not load a room');}});
await archive.link(()=>loader);await archive.evaluate();
directoryCloses=0;
assert.equal(node('roomTitle').textContent,'永旺家园');
assert.equal(node('archiveCover').src,'./assets/archive-hero.png');
assert.equal(node('enterRoomBtn').href,'#room');
choices[1].click();
assert.equal(location.hash,'','Selecting a room keeps the visitor on the homepage');
assert.equal(node('roomNumber').textContent,'ROOM 02');
assert.equal(node('roomTitle').textContent,'43号院');
assert.equal(node('archiveCover').src,'./assets/archive-courtyard43.jpg');
assert.equal(node('archiveCover').alt,'冬日雪景中的43号院');
assert.equal(node('enterRoomBtn').href,'#courtyard43');
assert.equal(choices[1]['aria-pressed'],'true');
assert.equal(choices[0]['aria-pressed'],'false');
assert.equal(directoryCloses,0,'Timeline selection does not close the room directory');
assert.equal(enterFocuses,0,'Timeline selection keeps focus on its button');
choices[3].click();
assert.equal(choices[3]['aria-pressed'],'true','Directory selection mirrors the timeline selection');
assert.equal(directoryCloses,1,'Selecting from the dialog closes it so the preview is visible');
assert.equal(enterFocuses,1,'Focus returns to the visible enter-room link after dialog selection');
assert.equal(node('courtyardRoom').hidden,true,'Selection does not reveal or instantiate the room');
console.log('Homepage room selection updates preview and entry link without entering a room.');
